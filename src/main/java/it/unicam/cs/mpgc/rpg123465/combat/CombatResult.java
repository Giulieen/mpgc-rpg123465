package it.unicam.cs.mpgc.rpg123465.combat;

/**
 * Rappresenta il possibile esito di un combattimento.
 */
public enum CombatResult {

    /**
     * Il giocatore ha vinto il combattimento.
     */
    VICTORY,

    /**
     * Il giocatore è stato sconfitto.
     */
    DEFEAT,

    /**
     * Il giocatore è riuscito a fuggire.
     */
    ESCAPE
}